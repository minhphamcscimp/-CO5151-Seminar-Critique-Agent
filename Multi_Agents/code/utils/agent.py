import backoff
import time
from openai import APIConnectionError, APIError, APIStatusError, OpenAI, RateLimitError
from .openai_utils import OutOfQuotaException
from .openai_utils import num_tokens_from_string, model2max_context

GEMINI_BASE_URL = "https://generativelanguage.googleapis.com/v1beta/openai/"
support_models = ["gemini-3.1-flash-lite"]


def log_retry(details: dict):
    error = details.get("exception")
    error_name = type(error).__name__ if error else "unknown error"
    print(
        f"API request failed ({error_name}); retry {details['tries']} "
        f"in {details['wait']:.1f}s.",
        flush=True,
    )


def give_up_retry(error: Exception) -> bool:
    if isinstance(error, APIStatusError):
        return error.status_code not in (429, 503)
    return False


class Agent:
    def __init__(self, model_name: str, name: str, temperature: float, sleep_time: float=0) -> None:
        """Create an agent

        Args:
            model_name(str): model name
            name (str): name of this agent
            temperature (float): higher values make the output more random, while lower values make it more focused and deterministic
            sleep_time (float): sleep because of rate limits
        """
        self.model_name = model_name
        self.name = name
        self.temperature = temperature
        self.memory_lst = []
        self.sleep_time = sleep_time

    @backoff.on_exception(
        backoff.expo,
        (RateLimitError, APIConnectionError, APIStatusError),
        max_tries=4,
        max_time=300,
        on_backoff=log_retry,
        giveup=give_up_retry,
    )
    def query(self, messages: "list[dict]", max_tokens: int, api_key: str) -> str:
        """make a query

        Args:
            messages (list[dict]): chat history in turbo format
            max_tokens (int): maximum completion tokens in the API call
            api_key (str): Gemini API key
        Raises:
            OutOfQuotaException: the Gemini API quota has been exhausted

        Returns:
            str: the return msg
        """
        time.sleep(self.sleep_time)
        assert self.model_name in support_models, f"Not support {self.model_name}. Choices: {support_models}"
        try:
            if self.model_name in support_models:
                print(f"{self.name}: waiting for {self.model_name} response...", flush=True)
                client = OpenAI(
                    api_key=api_key,
                    base_url=GEMINI_BASE_URL,
                    timeout=120.0,
                    max_retries=0,
                )
                response = client.chat.completions.create(
                    model=self.model_name,
                    messages=messages,
                    max_tokens=max_tokens,
                    reasoning_effort="low",
                )
                gen = response.choices[0].message.content
                if gen is None:
                    raise RuntimeError("Gemini returned an empty response.")
            return gen

        except RateLimitError as e:
            message = str(e).casefold()
            if any(phrase in message for phrase in ("quota", "resource_exhausted", "billing")):
                raise OutOfQuotaException() from e
            raise
        except APIStatusError as e:
            if not give_up_retry(e):
                raise
            raise RuntimeError(
                f"Gemini API returned HTTP {e.status_code}: {e.message}"
            ) from e

    def set_meta_prompt(self, meta_prompt: str):
        """Set the meta_prompt

        Args:
            meta_prompt (str): the meta prompt
        """
        self.memory_lst.append({"role": "system", "content": f"{meta_prompt}"})

    def add_event(self, event: str):
        """Add an new event in the memory

        Args:
            event (str): string that describe the event.
        """
        self.memory_lst.append({"role": "user", "content": f"{event}"})

    def add_memory(self, memory: str):
        """Monologue in the memory

        Args:
            memory (str): string that generated by the model in the last round.
        """
        self.memory_lst.append({"role": "assistant", "content": f"{memory}"})
        print(f"----- {self.name} -----\n{memory}\n")

    def ask(self):
        """Query for answer

        Args:
        """
        # query
        num_context_token = sum([num_tokens_from_string(m["content"], self.model_name) for m in self.memory_lst])
        remaining_tokens = model2max_context[self.model_name] - num_context_token
        if remaining_tokens <= 0:
            raise ValueError("The conversation exceeds the model's input token limit.")
        max_tokens = min(8192, remaining_tokens)
        return self.query(self.memory_lst, max_tokens, api_key=self.api_key)
